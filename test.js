// Starts the server, connects two real WebSocket clients, checks room isolation and presence sync.
const WebSocket = require("ws");
process.env.PORT = 3917;
const { server } = require("./server.js");
const url = "ws://localhost:3917/ws";
const open = () => new Promise(r => { const w = new WebSocket(url); w.last = null; w.errors = []; w.on("message", d => { const m = JSON.parse(d); if (m.type === "peers") w.last = m.peers; if (m.type === "hello") w.hello = m; if (m.type === "error") w.errors.push(m.code); }); w.on("open", () => r(w)); });
const wait = ms => new Promise(r => setTimeout(r, ms));
const ok = (c, msg) => { console.log((c ? "PASS " : "FAIL ") + msg); if (!c) process.exitCode = 1; };
const create = async () => (await (await fetch("http://localhost:3917/api/games", { method: "POST" })).json()).code;
(async () => {
  const g1 = await create(), g2 = await create();
  ok(/^[a-hjkmnp-z2-9]{5}$/.test(g1) && g1 !== g2, "server creates unique 5-char game codes");
  ok((await fetch("http://localhost:3917/api/games/" + g1)).status === 200, "created code is found");
  ok((await fetch("http://localhost:3917/api/games/paris7")).status === 404, "random code is not found");
  ok((await fetch("http://localhost:3917/api/games/" + g1.slice(0, 4) + (g1[4] === "a" ? "b" : "a"))).status === 404, "one-letter typo is not found");
  const x = await open();
  x.send(JSON.stringify({ type: "presence", patch: { n: "Typo", t: 1, st: "lobby", rc: "zzzzz" } }));
  await wait(200);
  ok(x.errors.includes("no_game") && (!x.last || x.last.length <= 1), "joining an unknown code over WebSocket is refused");
  x.close();
  const a = await open(), b = await open(), c = await open();
  a.send(JSON.stringify({ type: "presence", patch: { n: "Deepak", t: 1, st: "lobby", rc: g1 } }));
  b.send(JSON.stringify({ type: "presence", patch: { n: "Friend", t: 2, st: "lobby", rc: g1 } }));
  c.send(JSON.stringify({ type: "presence", patch: { n: "Other", t: 3, st: "lobby", rc: g2 } }));
  await wait(200);
  ok(a.hello && Math.abs(a.hello.now - Date.now()) < 5000, "hello carries server clock");
  ok(a.last.length === 2 && b.last.length === 2, "two players in paris7 see each other");
  ok(c.last.length === 1, "other room is isolated");
  ok(a.last[0].isMe && a.last[0].presence.n === "Deepak", "self entry first");
  a.send(JSON.stringify({ type: "presence", patch: { st: "play", cfg: { tn: "pres" }, a: 3 } }));
  await wait(150);
  const seen = b.last.find(p => !p.isMe);
  ok(seen && seen.presence.st === "play" && seen.presence.a === 3, "presence patch reaches friend");
  a.send(JSON.stringify({ type: "presence", patch: { a: null } }));
  await wait(150);
  ok(!("a" in b.last.find(p => !p.isMe).presence), "null patch deletes field");
  a.close(); await wait(200);
  ok(b.last.length === 1, "peer removed on disconnect");
  const res = await fetch("http://localhost:3917/healthz"); ok((await res.text()) === "ok", "healthz");
  const idx = await (await fetch("http://localhost:3917/")).text(); ok(idx.includes("Play with friends"), "page served");
  b.close(); c.close(); server.close(); setTimeout(() => process.exit(), 100);
})();
